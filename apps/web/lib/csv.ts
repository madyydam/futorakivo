/**
 * Parse a single CSV line according to RFC-4180 rules:
 * - Preserves spaces inside unquoted and quoted cells
 * - Preserves empty cells (`a,,c` -> `["a", "", "c"]`)
 * - Handles embedded commas inside quotes and doubled escaped quotes (`""`)
 */
export function parseCsvLine(line: string): string[] {
  const cells: string[] = [];
  let current = "";
  let inQuotes = false;

  for (let i = 0; i < line.length; i++) {
    const ch = line[i];
    if (inQuotes) {
      if (ch === '"') {
        if (line[i + 1] === '"') {
          current += '"';
          i++;
        } else {
          inQuotes = false;
        }
      } else {
        current += ch;
      }
    } else if (ch === '"') {
      inQuotes = true;
    } else if (ch === ",") {
      cells.push(current.trim());
      current = "";
    } else {
      current += ch;
    }
  }

  cells.push(current.trim());
  return cells;
}
